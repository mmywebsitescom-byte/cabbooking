export function filterFallbackCars(cars: Car[], params?: any): Car[] {
  if (!params) return cars;
  let result = [...cars];
  if (params.category && params.category !== 'all') {
    result = result.filter(c => c.category.toLowerCase() === params.category.toLowerCase());
  }
  if (params.transmission && params.transmission !== 'all') {
    result = result.filter(c => c.transmission.toLowerCase() === params.transmission.toLowerCase());
  }
  if (params.fuelType && params.fuelType !== 'all') {
    result = result.filter(c => c.fuelType.toLowerCase() === params.fuelType.toLowerCase());
  }
  if (params.maxPrice) {
    result = result.filter(c => c.pricing.dailyRate <= parseFloat(params.maxPrice));
  }
  if (params.search) {
    const q = params.search.toLowerCase();
    result = result.filter(c => c.name.toLowerCase().includes(q) || c.brand.toLowerCase().includes(q) || c.model.toLowerCase().includes(q));
  }
  return result;
}
